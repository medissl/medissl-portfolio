import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

export function importId(key) {
  const hex = createHash('sha256').update(`medissl-catalog-v1:${key}`).digest('hex');
  return `${hex.slice(0,8)}-${hex.slice(8,12)}-5${hex.slice(13,16)}-8${hex.slice(17,20)}-${hex.slice(20,32)}`;
}
const catalog = JSON.parse(readFileSync(new URL('../../src/components/mine/github-projects.json',import.meta.url),'utf8'));
export const curatedImport = catalog.map((p,index)=>({
  id:importId(p.id), legacy_key:p.id, slug:p.id, title:p.title, category:p.category,
  short_description:'', description:p.description, year:2026, tools:p.tools.split(' · '),
  cover_path:p.image, published:true, featured:false, display_order:index-catalog.length, carousel_order:index-catalog.length,
  platform:p.platform, features:p.features, repository_url:p.repository, demo_url:p.link,
  download_url:null, action_label:p.action, portrait:p.portrait, mineral:p.mineral, cover_alt:p.alt,
  project_media:[...(p.gallery?[{path:p.gallery,alt_text:p.alt}]:[]),
    ...(p.id==='sakiko'?[{path:'/mine/sakiko-classroom-day.webp',alt_text:"SAKIKO's daytime classroom"}]:[])]
    .map((m,i)=>({...m,id:importId(`${p.id}-media-${i}`),project_id:importId(p.id),caption:'',section:'gallery',display_order:i})),
}));

export function importSql() {
  const literal = value => `'${JSON.stringify(value).replaceAll("'","''")}'::jsonb`;
  const columns = ['id','legacy_key','slug','title','category','short_description','description','year','tools','cover_path','published','featured','display_order','carousel_order','platform','features','repository_url','demo_url','download_url','action_label','portrait','mineral','cover_alt'];
  const json = literal(curatedImport);
  return `-- Generated by docs/crystal-mine/curated-import.mjs. Insert-only, never an upsert.
begin;
-- Abort on collisions instead of guessing which existing content to overwrite.
do $$ begin
  if exists (
    select 1 from public.projects p join jsonb_to_recordset(${json}) x(id uuid,legacy_key text,slug text)
    on p.id=x.id or p.legacy_key=x.legacy_key or p.slug=x.slug
    where p.id<>x.id or p.legacy_key is distinct from x.legacy_key
  ) then raise exception 'Curated import conflicts with existing content; review before proceeding'; end if;
end $$;
with inserted as (
  insert into public.projects (${columns.join(',')})
  select ${columns.map(c=>`r.${c}`).join(',')} from jsonb_populate_recordset(null::public.projects,${json}) r
  on conflict(id) do nothing returning id
)
insert into public.project_media(id,project_id,path,caption,alt_text,section,display_order)
select m.id,m.project_id,m.path,m.caption,m.alt_text,m.section,m.display_order
from jsonb_populate_recordset(null::public.project_media,${literal(curatedImport.flatMap(p=>p.project_media))}) m
join inserted i on i.id=m.project_id;
commit;
`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL('../../supabase/migrations/20261019130926_import_curated_portfolio.sql',import.meta.url);
  writeFileSync(target,importSql());
  console.log(`Prepared ${curatedImport.length} projects; ${curatedImport.flatMap(p=>p.project_media).length} gallery images. No database connection made.`);
}
